// Compliance document generation. Port of Synthelion's compliance/documents.py.
//
// Four documents, each built from the LIVE configuration and the real audit trail rather than from a
// hand-maintained template:
//
//   technical-file   - EU AI Act Art. 11 / Annex IV system file
//   dpia             - GDPR Art. 35 data protection impact assessment
//   fria             - EU AI Act Art. 27 fundamental rights impact assessment
//   executive-report - periodic operational compliance report
//
// Every document is available as a JsonObject and as a PDF. The JSON is the source of truth; the PDF
// renders it, so nothing in a report exists only as pixels.
//
// These are pre-filled working drafts, NOT finished legal instruments. A DPIA and a FRIA require judgements
// - necessity, proportionality, residual-risk acceptance - that no engine can make on an organisation's
// behalf. What this supplies is every fact the assessment needs; the sections requiring human judgement are
// emitted explicitly as open items rather than filled with plausible text.
// ------------------------------------------------------------------------------
using System.Text.Json.Nodes;

namespace Caveman.Compliance;

public static class ComplianceDocuments
{
    public static readonly IReadOnlyList<string> Kinds = new[] { "technical-file", "dpia", "fria", "executive-report" };

    private const string Disclaimer =
        "Generated by the Caveman Compliance Engine from the live configuration and audit trail. It is a technical " +
        "working draft: sections requiring an organisational judgement are listed as open items and must be completed " +
        "and approved by the controller, the DPO or the appointed assessor before the document is relied upon.";

    private static string Now() => DateTime.UtcNow.ToString("yyyy-MM-dd HH:mm:ss") + " UTC";

    private static JsonArray Arr(IEnumerable<string> items) { var a = new JsonArray(); foreach (var i in items) a.Add(i); return a; }
    private static JsonArray Arr(IEnumerable<JsonNode?> items) { var a = new JsonArray(); foreach (var i in items) a.Add(i); return a; }

    public static JsonObject RuleToJson(ComplianceRule r)
    {
        var legal = new JsonArray();
        foreach (var l in r.Legal)
            legal.Add(new JsonObject { ["framework"] = l.Framework, ["article"] = l.Article, ["obligation"] = l.Obligation });
        return new JsonObject
        {
            ["id"] = r.Id, ["title"] = r.Title, ["category"] = r.Category.Wire(), ["backend"] = r.Backend,
            ["risk_level"] = r.RiskLevel.Wire(), ["action"] = r.Action.Wire(), ["scope"] = r.Scope.Wire(),
            ["enabled"] = r.Enabled, ["description"] = r.Description, ["legal"] = legal,
        };
    }

    private static JsonObject RowToJson(TraceabilityRow r) => new()
    {
        ["rule_id"] = r.RuleId, ["module"] = r.Module, ["category"] = r.Category, ["framework"] = r.Framework,
        ["article"] = r.Article, ["obligation"] = r.Obligation, ["enabled"] = r.Enabled, ["risk_level"] = r.RiskLevel, ["action"] = r.Action,
    };

    private static JsonArray Matrix(IEnumerable<TraceabilityRow> rows) => Arr(rows.Select(r => (JsonNode?)RowToJson(r)));

    private static JsonObject EngineSnapshot(ComplianceEngine e) => new()
    {
        ["status"] = ComplianceEngine.Wire(e.Status),
        ["fallback"] = ComplianceEngine.Wire(e.Fallback),
        ["language"] = e.Language,
        ["agent_profile"] = e.AgentProfile,
        ["system_prompt_override"] = !string.IsNullOrEmpty(e.SystemPromptOverride),
        ["rules"] = Arr(e.Rules.Select(r => (JsonNode?)RuleToJson(r))),
        ["rules_enabled"] = e.Rules.Count(r => r.Enabled),
        ["rules_total"] = e.Rules.Count,
    };

    // ── EU AI Act Art. 11 / Annex IV ─────────────────────────────────────

    public static JsonObject TechnicalFile(ComplianceEngine engine)
    {
        var chain = engine.Audit.VerifyChain();
        var version = typeof(ComplianceEngine).Assembly.GetName().Version?.ToString(3) ?? "unknown";
        return new JsonObject
        {
            ["document"] = "Technical Documentation (EU AI Act Art. 11, Annex IV)",
            ["generated_at"] = Now(),
            ["disclaimer"] = Disclaimer,
            ["system"] = new JsonObject
            {
                ["name"] = "Caveman AI Compliance Engine",
                ["version"] = version,
                ["role"] = "Security and governance gateway between client applications and third-party generative AI models.",
                ["deployment"] = "Self-hosted. Prompts and responses are processed locally; no telemetry is emitted to the vendor.",
            },
            ["engine"] = EngineSnapshot(engine),
            // Annex IV asks for the history of what the model was told, not just the current text.
            ["system_prompt_registry"] = engine.Instructions.Summary(),
            ["guardrails"] = Arr(engine.Rules.Select(r => (JsonNode?)RuleToJson(r))),
            ["traceability_matrix"] = Matrix(ComplianceRules.TraceabilityMatrix(engine.Rules)),
            ["coverage_gaps"] = Matrix(ComplianceRules.CoverageGaps(engine.Rules)),
            // A control switched on whose guard is switched off elsewhere is the one thing a technical file
            // must never quietly omit.
            ["backend_health"] = Arr(engine.BackendHealthReport().Select(h => (JsonNode?)h.ToJson())),
            ["ineffective_controls"] = Arr(engine.IneffectiveRules().Select(h => (JsonNode?)h.ToJson())),
            ["record_keeping"] = new JsonObject
            {
                ["mechanism"] = "Hash-chained append-only JSONL audit trail (Art. 12).",
                ["entries"] = chain.Entries,
                ["chain_valid"] = chain.Valid,
                ["chain_note"] = string.IsNullOrEmpty(chain.Reason) ? "No tampering detected." : chain.Reason,
                ["content_policy"] = "Only a SHA-256 fingerprint of each payload is stored, never the prompt or response text.",
            },
            ["human_oversight"] = new JsonObject
            {
                ["article"] = "EU AI Act Art. 14",
                ["mechanisms"] = Arr(OversightMechanisms),
            },
            ["open_items"] = Arr(new[]
            {
                "Assign the intended purpose and the risk classification of each connected use case (Art. 6 and Annex III).",
                "Record the accuracy metrics and operational limits communicated to users (Art. 13).",
                "Attach the provider documentation of each connected third-party model (Art. 53).",
            }),
        };
    }

    private static readonly string[] OversightMechanisms =
    {
        "Gated actions: operations classified as requiring approval are refused by the policy engine until an operator authorises them out of band.",
        "Engine status can be set to inactive or staging at any time, taking the gateway out of enforcement without a redeploy.",
        "Every decision is reviewable in the audit trail.",
    };

    // ── GDPR Art. 35 ─────────────────────────────────────────────────────

    public static JsonObject Dpia(ComplianceEngine engine, DateTimeOffset? since = null)
    {
        var stats = engine.Audit.Statistics(since);
        var privacyRules = engine.Rules.Where(r => r.Category == RuleCategory.Privacy).ToList();
        var observed = new JsonObject();
        if (stats.ByCategory.TryGetValue("privacy", out var privacyFindings)) observed["privacy"] = privacyFindings;

        return new JsonObject
        {
            ["document"] = "Data Protection Impact Assessment (GDPR Art. 35)",
            ["generated_at"] = Now(),
            ["disclaimer"] = Disclaimer,
            ["processing_description"] = new JsonObject
            {
                ["purpose"] = "Filtering and governance of prompts and responses exchanged with third-party generative AI models.",
                ["nature"] = "Automated inspection in transit. Payload text is inspected in memory and is not persisted by the engine.",
                ["data_categories_observed"] = Arr(stats.ByRule.Keys.OrderBy(k => k, StringComparer.Ordinal)),
                ["findings_in_period"] = observed,
            },
            ["measures"] = new JsonObject
            {
                ["minimisation"] = Arr(privacyRules.Select(r => (JsonNode?)RuleToJson(r))),
                ["storage"] = "The audit trail stores a SHA-256 fingerprint of each payload, never the text - the log cannot itself become a source of personal data.",
                ["transfers"] = "Personal data detected by the engine is redacted before the payload reaches a third-party model endpoint.",
            },
            ["necessity_and_proportionality"] = new JsonObject
            {
                ["status"] = "requires human assessment",
                ["note"] = "Whether the processing is necessary and proportionate to its purpose is a controller judgement and is deliberately not auto-filled.",
            },
            ["risks"] = new JsonObject
            {
                ["identified"] = Arr(new[]
                {
                    "Residual personal data in free text not matched by any detector.",
                    "Re-identification from combinations of individually non-identifying fields.",
                    "Onward processing by the third-party model provider under its own terms.",
                }),
                ["mitigations"] = Arr(new[]
                {
                    $"{privacyRules.Count} privacy control(s) configured; {privacyRules.Count(r => r.Enabled)} currently enabled.",
                    "Detection is confirmed by checksum and context keyword before masking, limiting both false positives and silent misses.",
                }),
                ["residual_risk_acceptance"] = "requires human assessment",
            },
            ["statistics"] = stats.ToJson(),
            ["open_items"] = Arr(new[]
            {
                "Record the lawful basis for the processing (Art. 6).",
                "Record the retention period applied to the audit trail.",
                "Record the outcome of the consultation with the DPO (Art. 35(2)).",
            }),
        };
    }

    // ── EU AI Act Art. 27 ────────────────────────────────────────────────

    public static JsonObject Fria(ComplianceEngine engine, DateTimeOffset? since = null)
    {
        var stats = engine.Audit.Statistics(since);
        IEnumerable<string> Ids(params RuleCategory[] cats) => engine.Rules.Where(r => cats.Contains(r.Category) && r.Enabled).Select(r => r.Id);

        return new JsonObject
        {
            ["document"] = "Fundamental Rights Impact Assessment (EU AI Act Art. 27)",
            ["generated_at"] = Now(),
            ["disclaimer"] = Disclaimer,
            ["deployment_context"] = new JsonObject
            {
                ["description"] = "Gateway mediating employee and application access to generative AI models.",
                ["affected_persons"] = "requires human assessment",
                ["frequency_and_duration"] = $"{stats.TotalCalls} transaction(s) recorded in the reporting period.",
            },
            ["rights_assessment"] = new JsonArray
            {
                new JsonObject
                {
                    ["right"] = "Protection of personal data (Charter Art. 8)",
                    ["impact"] = "Mitigated by automated redaction before third-party transmission.",
                    ["controls"] = Arr(Ids(RuleCategory.Privacy)),
                },
                new JsonObject
                {
                    ["right"] = "Non-discrimination (Charter Art. 21)",
                    ["impact"] = "Model output may reflect bias present in the underlying model.",
                    ["controls"] = Arr(Ids(RuleCategory.Safety, RuleCategory.Content)),
                    ["note"] = "The engine screens output but does not evaluate the model for bias; that assessment belongs to the model provider's documentation.",
                },
                new JsonObject
                {
                    ["right"] = "Human dignity and freedom of expression",
                    ["impact"] = "Content screening can over-block legitimate expression.",
                    ["controls"] = Arr(new[] { "Engine staging mode allows a policy to be measured before it enforces." }),
                },
                new JsonObject
                {
                    ["right"] = "Right to an effective remedy",
                    ["impact"] = "Affected persons must be able to contest an automated refusal.",
                    ["controls"] = Arr(new[] { "Every decision is recorded with its rule id and risk level, making a refusal explainable after the fact." }),
                    ["note"] = "requires human assessment - the complaint channel is organisational.",
                },
            },
            ["oversight_measures"] = Arr(OversightMechanisms),
            ["statistics"] = stats.ToJson(),
            ["open_items"] = Arr(new[]
            {
                "Identify the categories of persons affected in this deployment.",
                "Define the complaint and redress channel offered to them.",
                "Notify the market surveillance authority where Art. 27(3) applies.",
            }),
        };
    }

    // ── Periodic report ──────────────────────────────────────────────────

    public static JsonObject ExecutiveReport(ComplianceEngine engine, int days = 30)
    {
        var since = DateTimeOffset.UtcNow.AddDays(-days);
        var stats = engine.Audit.Statistics(since);
        var chain = engine.Audit.VerifyChain();
        return new JsonObject
        {
            ["document"] = $"Executive Compliance Report - last {days} day(s)",
            ["generated_at"] = Now(),
            ["period_days"] = days,
            ["engine"] = new JsonObject
            {
                ["status"] = ComplianceEngine.Wire(engine.Status),
                ["fallback"] = ComplianceEngine.Wire(engine.Fallback),
                ["rules_enabled"] = engine.Rules.Count(r => r.Enabled),
                ["rules_total"] = engine.Rules.Count,
            },
            ["statistics"] = stats.ToJson(),
            ["audit_chain"] = chain.ToJson(),
            ["coverage_gaps"] = Matrix(ComplianceRules.CoverageGaps(engine.Rules)),
        };
    }

    /// <summary>Generates one of <see cref="Kinds"/>.</summary>
    public static JsonObject Generate(string kind, ComplianceEngine engine, int days = 30, DateTimeOffset? since = null) => kind switch
    {
        "technical-file" => TechnicalFile(engine),
        "dpia" => Dpia(engine, since),
        "fria" => Fria(engine, since),
        "executive-report" => ExecutiveReport(engine, days),
        _ => throw new ArgumentException($"unknown document '{kind}'; choose from {string.Join(", ", Kinds)}", nameof(kind)),
    };
}
